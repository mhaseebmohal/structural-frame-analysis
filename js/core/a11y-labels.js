/* ══════════════════════════════════════════════════════════════════════
   a11y-labels.js — attach the labels that are already on screen.

   index.html writes its dialog rows as

       <div class="form-row"><label>Node</label><select id="settle-node-sel">…

   The label is visible and correct, but it carries no `for`, so nothing
   connects it to the field. Two consequences:

     · a screen reader announces the control with no name at all — "combo box",
       "edit text" — and on a form of fifteen numeric inputs that is unusable;
     · clicking the label text does nothing, where on a properly associated
       label it focuses the field (and toggles a checkbox). That is a plain
       usability loss for everyone, not only assistive-tech users.

   565 of the 654 controls in this file were in that state. Rather than hand-
   write 565 aria-labels — duplicating text that already exists on screen, and
   creating 565 things to keep in sync with it — this walks the DOM and wires
   each visible label to the field it already sits beside.

   The rule is the one the markup already follows: a label precedes its field.
   Pairing is bounded to the row the two share, so a label with no field of its
   own cannot capture the next row's.

   Controls generated by JS (the node / member / section tables) are named in
   their own renderers instead — their text comes from the row's data, not from
   a label on screen.

   Load AFTER app.js. Exposes window.A11yLabels.
   ══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var CTRL = 'input:not([type=hidden]),select,textarea';

  // Scanning backwards for a control's name stops dead at any of these. Text
  // belonging to something else is not this control's name, however close it
  // sits: a row ending `<button>None</button><span flex:1></span><select>` gave
  // the member-type filter the name "None", read off the deselect button.
  var STOP = 'label,button,a,[role=button],' + CTRL;
  var seq = 0;

  /**
   * A real, durable accessible name.
   *
   * `placeholder` and `title` are deliberately NOT counted. Both do act as a
   * last-resort name, but a placeholder vanishes the moment the field has a
   * value and a title needs a hover — so where the page also has a visible
   * label, the label is the better name and should still be wired up. The
   * click-to-focus behaviour only comes from a real association anyway.
   */
  function hasName(el) {
    if (el.getAttribute('aria-label') || el.getAttribute('aria-labelledby')) return true;
    if (el.id && document.querySelector('label[for="' + CSS.escape(el.id) + '"]')) return true;
    if (el.closest('label')) return true;
    return false;
  }

  /** The weaker kind — enough that we should not invent a name over the top. */
  function hasFallbackName(el) {
    return !!(el.getAttribute('title') || el.getAttribute('placeholder'));
  }

  function textOf(el) {
    return (el.textContent || '').replace(/\s+/g, ' ').trim();
  }

  function ensureId(el) {
    if (!el.id) el.id = 'a11y-f' + (++seq);
    return el.id;
  }

  /** A free label — one not already pointing at a field, and with something to say. */
  function isFree(el) {
    return el && el.tagName === 'LABEL' && !el.getAttribute('for') && !!textOf(el);
  }

  /** Is the label close enough to this control to be describing it? */
  function sameRow(label, ctrl) {
    var lp = label.parentElement, cp = ctrl.parentElement;
    if (!lp || !cp) return false;
    return lp === cp || lp.contains(ctrl) || cp.contains(label);
  }

  function attach(label, ctrl) {
    label.setAttribute('for', ensureId(ctrl));
  }

  /**
   * Wire visible labels to their controls within `root`.
   *
   * Walks labels and controls in document order: remember the last label seen,
   * and give it to the next unnamed control — provided the two share a row.
   * A label that is consumed is not offered again, so a row of several fields
   * takes several labels in order rather than all sharing the first.
   */
  function wireLabels(root) {
    var all = root.querySelectorAll('label,' + CTRL);
    var pending = null, wired = 0;

    for (var i = 0; i < all.length; i++) {
      var el = all[i];

      if (el.tagName === 'LABEL') {
        if (isFree(el)) pending = el;
        continue;
      }

      if (hasName(el)) { pending = null; continue; }

      if (pending && sameRow(pending, el)) { attach(pending, el); wired++; }
      pending = null;
    }
    return wired;
  }

  /**
   * The other convention on this page: `<input type=checkbox><label>Show grid`,
   * where the label follows the control it names. Only ever consulted for a
   * control the forward pass left unnamed, so it cannot steal a label.
   */
  function wireTrailingLabels(root) {
    var list = root.querySelectorAll(CTRL), wired = 0;

    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (hasName(el)) continue;

      var n = el.nextSibling;
      while (n && n.nodeType === 3 && !n.textContent.trim()) n = n.nextSibling;
      if (isFree(n) && sameRow(n, el)) { attach(n, el); wired++; }
    }
    return wired;
  }

  /**
   * Anything still unnamed, labelled from the text immediately before it —
   * "Units:" ahead of the unit switcher, and similar rows that use a bare
   * <span> or text node where a <label> would have done.
   *
   * The walk stops at the first control or <label> it meets. Without that it
   * reads straight through them to whatever text comes next, and in a row like
   *
   *     <label>Grid line color</label><input type=color><select>…
   *
   * the line-STYLE dropdown came out named "Grid line color" — a confident,
   * wrong name, which is worse for a screen-reader user than no name at all.
   * A control that shares its row with another control's label has no name of
   * its own here, and is reported rather than guessed at. The same goes for a
   * neighbouring button's caption, which is why STOP covers those too.
   */
  function labelFromLeadingText(root) {
    var list = root.querySelectorAll(CTRL), named = 0;

    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (hasName(el) || hasFallbackName(el)) continue;

      var t = '';
      for (var n = el.previousSibling; n && !t; n = n.previousSibling) {
        if (n.nodeType === 1 && (n.matches(STOP) || n.querySelector(STOP))) break;
        t = (n.textContent || '').replace(/\s+/g, ' ').trim();
      }
      // A trailing colon reads as punctuation, not as part of the name.
      t = t.replace(/[:：]\s*$/, '');
      if (t && t.length <= 40) { el.setAttribute('aria-label', t); named++; }
    }
    return named;
  }

  /** Controls still with no name of any kind — reported, never guessed at. */
  function unnamed(root) {
    return [].slice.call((root || document).querySelectorAll(CTRL)).filter(function (el) {
      return !hasName(el) && !hasFallbackName(el);
    });
  }

  function run(root) {
    root = root || document;
    var wired = wireLabels(root) + wireTrailingLabels(root);
    var fromText = labelFromLeadingText(root);
    return { wired: wired, fromText: fromText, stillUnnamed: unnamed(root).length };
  }

  function init() { run(document); }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();

  window.A11yLabels = {
    // Call after inserting new markup that contains labelled fields.
    refresh: run,
    unnamed: unnamed
  };
})();
